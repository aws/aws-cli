class NodeRuntime(Runtime):
    family = 'nodejs'
    display_name = 'Node.js'
    aliases = ('node', 'nodejs')
    versions = (constants.DEFAULT_RUNTIME,)
    entry_env_var = constants.ENTRYPOINT_ENV_VAR
    default_entry = constants.RUNTIME_ENTRY_FILE
    docs = _DOCS

    def detect(self, source_dir):
        candidates = ('package.json',) + constants.ENTRY_POINT_CANDIDATES
        return any(
            os.path.isfile(os.path.join(source_dir, name))
            for name in candidates
        )

    def resolve_entry(self, source_dir, explicit=None):
        return select(resolve_entry_point(source_dir, explicit))

    def customer_entry(self, value, source_dir):
        # the runtime loads the named file directly, so nothing is generated.
        value = PureWindowsPath(value).as_posix()
        verify_entrypoint_in_tree(source_dir, value)
        return EntrySelection(display=value, env={self.entry_env_var: value})

    def scaffold_files(self, function_name):
        return {
            SCAFFOLD_ENTRY: _server_ts(),
            'package.json': _package_json(function_name),
        }

    def scaffold_entry(self):
        return SCAFFOLD_ENTRY


RUNTIME = NodeRuntime()
